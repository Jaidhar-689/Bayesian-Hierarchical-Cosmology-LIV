def summarize_posterior(samples):
    mean = np.mean(samples)
    p68 = np.percentile(samples, [16, 84])
    p95 = np.percentile(samples, [2.5, 97.5])

    return {
        "center": mean,
        "p68": p68,
        "p95": p95,
        "err+_68": p68[1] - mean,
        "err-_68": mean - p68[0],
        "err+_95": p95[1] - mean,
        "err-_95": mean - p95[0],
    }

def results_table(results):
    rows = []
    for name, r in results.items():
        rows.append({
            "parameter": name,
            "mean": r["center"],
            "+68%": r["err+_68"],
            "-68%": r["err-_68"],
            "+95%": r["err+_95"],
            "-95%": r["err-_95"],
        })
    return pd.DataFrame(rows)

