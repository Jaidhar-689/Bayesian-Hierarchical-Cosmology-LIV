def chi2_nu_pdf(chi2_nu, nu):
    prefactor = (nu**(nu/2)) / (2**(nu/2) * gamma(nu/2))
    return prefactor * chi2_nu**((nu - 2)/2) * np.exp(-nu * chi2_nu / 2)

def chi2_nu_cdf(chi2_nu, nu):
    return gammainc(nu / 2, nu * chi2_nu / 2)

